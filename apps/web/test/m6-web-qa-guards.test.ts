// Independent QA of the web side of HCP-SPEC-005 (application stacks): source scans over the new pages,
// components and BFF routes. Node-only: nothing is rendered, no mock is needed.
import fs from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";

const web = path.resolve(__dirname, "..");
const src = path.join(web, "src");

function files(dir: string): string[] {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const full = path.join(dir, e.name);
    return e.isDirectory() ? files(full) : /\.tsx?$/.test(e.name) ? [full] : [];
  });
}
const rel = (f: string) => path.relative(src, f).split(path.sep).join("/");
const read = (f: string) => fs.readFileSync(f, "utf-8");
// Comments are prose, not code.
const code = (f: string) => read(f).replace(/\/\*[\s\S]*?\*\//g, "").replace(/(^|[^:])\/\/.*$/gm, "$1");

const adminRoutes = files(path.join(src, "app/api/admin/app-templates"));
const customerRoutes = files(path.join(src, "app/api/bff/orgs/[orgId]/app-stacks"));
const routeFiles = [...adminRoutes, ...customerRoutes];
const customerFiles = [...files(path.join(src, "app/apps")), ...files(path.join(src, "components/app-stacks"))];
const adminFiles = [
  ...files(path.join(src, "components/admin")).filter((f) => /\/(app-template-[^/]*|templates-tabs\.tsx)$/.test(rel(f))),
  ...files(path.join(src, "app/admin/templates/apps")),
];
const allNew = [...routeFiles, ...customerFiles, ...adminFiles];

const EXPECTED_ROUTES = [
  "app/api/admin/app-templates/[templateId]/archive/route.ts",
  "app/api/admin/app-templates/[templateId]/route.ts",
  "app/api/admin/app-templates/[templateId]/versions/route.ts",
  "app/api/admin/app-templates/route.ts",
  "app/api/admin/app-templates/validate/route.ts",
  "app/api/bff/orgs/[orgId]/app-stacks/[stackId]/[action]/route.ts",
  "app/api/bff/orgs/[orgId]/app-stacks/[stackId]/components/[componentKey]/logs/route.ts",
  "app/api/bff/orgs/[orgId]/app-stacks/[stackId]/domains/[domainId]/route.ts",
  "app/api/bff/orgs/[orgId]/app-stacks/[stackId]/domains/route.ts",
  "app/api/bff/orgs/[orgId]/app-stacks/[stackId]/plan/route.ts",
  "app/api/bff/orgs/[orgId]/app-stacks/[stackId]/route.ts",
  "app/api/bff/orgs/[orgId]/app-stacks/[stackId]/secrets/route.ts",
  "app/api/bff/orgs/[orgId]/app-stacks/route.ts",
].sort();

describe("M6 web guards: the scans really see the new files", () => {
  it("covers every new page, component and route (a moved directory would make the scans vacuous)", () => {
    expect(routeFiles.length).toBe(EXPECTED_ROUTES.length);
    expect(files(path.join(src, "app/apps")).map(rel).sort()).toEqual(
      [
        "app/apps/[stackId]/page.tsx",
        "app/apps/layout.tsx",
        "app/apps/new/[templateId]/page.tsx",
        "app/apps/new/page.tsx",
        "app/apps/not-found.tsx",
        "app/apps/page.tsx",
      ],
    );
    expect(files(path.join(src, "components/app-stacks")).length).toBeGreaterThanOrEqual(14);
    expect(adminFiles.map(rel)).toEqual(
      expect.arrayContaining([
        "components/admin/templates-tabs.tsx",
        "components/admin/app-template-editor.tsx",
        "app/admin/templates/apps/page.tsx",
      ]),
    );
  });
});

describe("M6 web guards: browser-side hazards", () => {
  it.each([
    ["raw HTML injection", /dangerouslySetInnerHTML|\.innerHTML|\binnerHTML\b|insertAdjacentHTML|document\.write/],
    ["browser storage and cookies", /\blocalStorage\b|\bsessionStorage\b|\bindexedDB\b|document\.cookie/],
    ["eval-like code", /\beval\s*\(|new Function\s*\(/],
  ])("no new file uses %s", (_name, pattern) => {
    for (const f of allNew) expect(code(f), rel(f)).not.toMatch(pattern);
  });

  it("no route file mints a key: the Idempotency-Key is the browser's, never generated by the BFF", () => {
    for (const f of routeFiles) expect(code(f), rel(f)).not.toMatch(/randomUUID|uuid|Math\.random|nanoid/i);
  });

  it("the browser never sets a secret value into a URL or query string", () => {
    for (const f of customerFiles) {
      expect(code(f), rel(f)).not.toMatch(/[?&](value|secret|password)=/i);
    }
  });
});

describe("M6 web guards: the BFF route inventory", () => {
  it("is exactly the thirteen routes of the design, no more (no ports, backups, Git, health, admin stack routes)", () => {
    expect(routeFiles.map(rel).sort()).toEqual(EXPECTED_ROUTES);
  });

  it("every app route goes through the shared forwarding helpers and exports only HTTP verbs", () => {
    for (const f of routeFiles) {
      const c = code(f);
      expect(c, rel(f)).toMatch(/\bforward(Idempotent|ToUpstream)\b/);
      expect(c, rel(f)).toMatch(/from "@\/lib\/bff-(idempotent|proxy)"/);
      // no hand-rolled upstream call that would skip session, CSRF or Origin checks
      expect(c, rel(f)).not.toMatch(/\bfetch(Upstream)?\s*\(/);
      expect(c, rel(f)).not.toMatch(/\bGET\b[^\n]*\bPOST\b[^\n]*=>|export (const|async function) (PUT|HEAD|OPTIONS)\b/);
    }
  });

  it("routes that forward a body veto it with a contract schema (value import from @hosting-panel/contracts)", () => {
    for (const f of routeFiles) {
      const c = code(f);
      if (/"(POST|PATCH|DELETE)"/.test(c)) {
        expect(c, rel(f)).toMatch(/from "@hosting-panel\/contracts"/);
        expect(c, rel(f)).toMatch(/\.safeParse\(/);
      }
    }
  });

  it("every route with a path parameter validates the segments before building the upstream path", () => {
    for (const f of customerRoutes) {
      const c = code(f);
      if (!/\bparams\b/.test(c)) continue;
      // forwardIdempotent validates segments itself (passed as its 2nd argument); forwardToUpstream does not.
      if (/forwardToUpstream\(/.test(c)) expect(c, rel(f)).toMatch(/validatePathSegments\(/);
      if (/forwardIdempotent\(/.test(c)) expect(c, rel(f)).toMatch(/forwardIdempotent\(\s*req,\s*\{[^}]*\}/);
    }
  });

  it("the queueing-action route is closed over its own keys (__proto__ and constructor are unknown actions)", () => {
    const c = code(path.join(src, "app/api/bff/orgs/[orgId]/app-stacks/[stackId]/[action]/route.ts"));
    expect(c).toMatch(/Object\.hasOwn\(/);
    expect(c).not.toMatch(/\bin\s+APP_STACK_ACTIONS\b/);
    for (const a of ["deploy", "start", "stop", "restart", "upgrade", "rollback"]) expect(c).toMatch(new RegExp(`\\b${a}:`));
    for (const a of ["delete", "plan", "secrets", "domains", "logs", "ports", "backups", "git"]) expect(c).not.toMatch(new RegExp(`\\b${a}:\\s*\\{`));
  });

  it("only the two idempotent verbs of the design carry no Idempotency-Key (secrets, domains, plan, logs)", () => {
    const sync = ["secrets", "domains", "plan", "components"];
    for (const f of customerRoutes) {
      const r = rel(f);
      const isSync = sync.some((s) => r.includes(`/${s}/`) || r.includes(`/${s}`));
      const c = code(f);
      if (isSync) expect(c, r).not.toMatch(/forwardIdempotent/);
      else expect(c, r).toMatch(/forwardIdempotent/);
    }
  });
});

describe("M6 web guards: no UI for Wave P, Wave G or stack backups", () => {
  const banned = /stackPublicPortsAvailable|gitBuildsAvailable|\/ports\b|\/backups\b|\/git\b|publicPort|gitUrl|gitRef|buildContext/;
  it("none of the new files mentions the future waves", () => {
    for (const f of allNew) expect(code(f), rel(f)).not.toMatch(banned);
  });

  it("the only capability flag the customer files read is applicationStacksAvailable", () => {
    for (const f of customerFiles) {
      const flags = [...code(f).matchAll(/\b(application\w+Available|stack\w+Available|git\w+Available)\b/g)].map((m) => m[1]);
      for (const flag of flags) expect(flag, rel(f)).toBe("applicationStacksAvailable");
    }
  });

  it("the admin files read only applicationTemplatesAvailable", () => {
    for (const f of adminFiles) {
      const flags = [...code(f).matchAll(/\b(application\w+Available|stack\w+Available|git\w+Available)\b/g)].map((m) => m[1]);
      for (const flag of flags) expect(flag, rel(f)).toBe("applicationTemplatesAvailable");
    }
  });
});

describe("M6 web guards: the organisation never comes from the URL", () => {
  it("no /apps file reads an org id from params, searchParams or a cookie, and the folder has no [org…] segment", () => {
    const pages = files(path.join(src, "app/apps"));
    expect(pages.length).toBeGreaterThanOrEqual(6);
    for (const f of pages) {
      const c = read(f);
      const r = rel(f);
      expect(c, r).not.toMatch(/params\b[^\n;]*\b(orgId|organizationId|orgSlug)\b|\b(orgId|organizationId|orgSlug)\b[^\n;]*=\s*await\s+(params|searchParams)/i);
      expect(r.includes("[org"), r).toBe(false);
      expect(c, r).not.toMatch(/searchParams/);
      if (/\borgId\b/.test(c)) expect(c, r).toMatch(/getCustomerContext\(\)/);
      expect([...c.matchAll(/cookies\(\)\)?\.get\(([^)]+)\)/g)], r).toEqual([]);
    }
  });

  it("customer components never take an org id from a cookie or location", () => {
    for (const f of files(path.join(src, "components/app-stacks"))) {
      expect(code(f), rel(f)).not.toMatch(/cookies\(\)|location\.(pathname|search|href)|useSearchParams|useParams/);
    }
  });

  it("every /apps page runs through the customer context (the shell does the login and support guards)", () => {
    for (const f of files(path.join(src, "app/apps")).filter((p) => /(page|layout)\.tsx$/.test(p))) {
      expect(code(f), rel(f)).toMatch(/getCustomerContext\(\)/);
    }
  });
});

describe("M6 web guards: what a customer is never shown", () => {
  it("no customer file renders the API's errorMessage or a raw error message", () => {
    for (const f of customerFiles) {
      const c = code(f);
      expect(c, rel(f)).not.toMatch(/\.errorMessage\b|\berror\.message\b|\berr\.message\b|\be\.message\b/);
    }
  });

  it("the progress view never renders the English `label` of an operation step (catalog texts only)", () => {
    for (const f of customerFiles.filter((p) => /progress|actions|delete|status/.test(path.basename(p)))) {
      expect(code(f), rel(f)).not.toMatch(/\b(step|s|st)\.label\b/);
    }
  });

  it("the page-level and shell files render no server error object directly", () => {
    for (const f of files(path.join(src, "app/apps"))) {
      expect(code(f), rel(f)).not.toMatch(/JSON\.stringify\((error|err|result|res)\b|\.stack\b/);
    }
  });
});

describe("M6 web guards: the copy scan covers the new folders", () => {
  const uiCopy = read(path.join(web, "test/ui-copy.test.ts"));
  const dirsBlock = uiCopy.match(/const dirs = \[([\s\S]*?)\]\.map/)?.[1] ?? "";
  const sectionsBlock = uiCopy.match(/const sections = \[([\s\S]*?)\] as const/)?.[1] ?? "";

  it("ui-copy.test.ts scans app/apps and components/app-stacks", () => {
    expect(dirsBlock).toContain('"app/apps"');
    expect(dirsBlock).toContain('"components/app-stacks"');
  });

  it("ui-copy.test.ts scans the `apps` message section", () => {
    expect(sectionsBlock).toMatch(/"apps"/);
  });

  it("the old dirs are still scanned (the edit only added)", () => {
    for (const d of ["app/sites", "components/customer", "components/shared"]) expect(dirsBlock).toContain(`"${d}"`);
  });
});
